loadSuggestCss = function() {
	var headobj = document.getElementsByTagName("head").item(0);
	var linkobjs = document.getElementsByTagName("link");
	var already_loaded = false;
	for (var i = 0; i < linkobjs.length; i++) {
		if (linkobjs.item(i).getAttribute('href')) {
			if (linkobjs.item(i).getAttribute('href').indexOf('/appletw/2011/support/css/suggest2.css') != -1) {
				already_loaded = true;
			}
		}
	}
	if (headobj && !already_loaded) {
		var host = (window.location.protocol == "https:") ? "https://ssl.apple.com" : "http://images.apple.com";
		var linkobj = document.createElement("link");
		linkobj.setAttribute("rel", "stylesheet");
		linkobj.setAttribute("href", host + "/appletw/2011/support/css/suggest2.css");
		linkobj.setAttribute("type", "text/css");
		linkobj.setAttribute("charset", "utf-8");
		headobj.appendChild(linkobj);
	}
};
loadSuggestCss();
