var ACQLFix = function() {
	
	var cookie = document.cookie.match(new RegExp('(^|;)\\s*POD=([^;\\s]*)'));
	if (cookie) {
		var pod = unescape(cookie[2]);
		var country = pod.split('~')[0].toLowerCase();
		
		switch (country) {
			case 'at':
				ACQLData.de[4].LINK = "http://apple.com/at/support/contact/";
				break;
			case 'ch':
				ACQLData.de[4].LINK = "http://apple.com/chde/support/contact/";
				ACQLData.fr[4].LINK = "http://apple.com/chfr/support/contact/";
				break;
			case 'be':
				ACQLData.fr[4].LINK = "http://apple.com/befr/support/contact/";
				break;
			case 'ca':
				ACQLData.en[4].LINK = "http://apple.com/ca/support/contact/";
				ACQLData.fr[4].LINK = "http://apple.com/ca/fr/support/contact/";
				break;
			case 'mx':
				ACQLData.es[4].LINK = "http://apple.com/mx/support/contact/";
				break;
			case 'la':
				ACQLData.es[4].LINK = "http://apple.com/la/support/contact/";
				break;
			default: 
				break;
		}
	}
}

